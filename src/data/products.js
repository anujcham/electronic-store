const buildProduct = ({
  id,
  slug,
  name,
  brand,
  category,
  subcategory,
  price,
  originalPrice,
  condition,
  rating,
  reviewCount,
  images,
  shortDescription,
  description,
  storage,
  color,
  availableColors,
  availableStorage,
  stock,
  featured,
  tags,
  conditionOptions,
  batteryOptions,
  simOptions,
  shippingIncluded = true,
  deliveryRange = "2-4 working days",
  warrantyMonths = 12,
  variantPricing,
}) => {
  const normalizedColors = availableColors && availableColors.length ? availableColors : [color].filter(Boolean);
  const normalizedStorage = availableStorage && availableStorage.length ? availableStorage : [storage].filter(Boolean);

  const generatedVariantPricing =
    variantPricing && variantPricing.length
      ? variantPricing
      : normalizedStorage.flatMap((storageOption, storageIndex) =>
          normalizedColors.map((colorOption, colorIndex) => ({
            storage: storageOption || null,
            color: colorOption || null,
            condition: conditionOptions?.[0] || condition,
            battery: batteryOptions?.[0] || "Optimal",
            sim: simOptions?.[0] || "Single SIM",
            price: price + storageIndex * 35 + colorIndex * 15,
            originalPrice: originalPrice + storageIndex * 45 + colorIndex * 20,
            stock: Math.max(1, stock - storageIndex - colorIndex),
            warrantyMonths,
            deliveryRange,
            shippingIncluded,
          }))
        );

  return {
    id,
    slug,
    name,
    brand,
    category,
    subcategory,
    price,
    originalPrice,
    discountPercentage: Math.round(((originalPrice - price) / originalPrice) * 100),
    condition,
    rating,
    reviewCount,
    images,
    shortDescription,
    description,
    storage,
    color,
    availableColors: normalizedColors,
    availableStorage: normalizedStorage,
    stock,
    featured,
    tags,
    conditionOptions: conditionOptions || ["Like New", "Excellent", "Very Good", "Good"],
    batteryOptions: batteryOptions || ["Optimal (85%+)", "New Replacement Battery (100%)"],
    simOptions: simOptions || ["Single SIM", "Dual-SIM (physical SIM + eSIM)"],
    shippingIncluded,
    deliveryRange,
    warrantyMonths,
    variantPricing: generatedVariantPricing,
  };
};

